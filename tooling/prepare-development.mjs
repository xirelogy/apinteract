import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const repositoryRoot = resolve(import.meta.dirname, "..");
const runtimeRoot = resolve(repositoryRoot, "var");
const configurationRoot = resolve(runtimeRoot, "config");
const publicOrigin =
  process.env.APINTERACT_DEV_PUBLIC_ORIGIN ?? "http://localhost:5173";

validatePublicOrigin(publicOrigin);

await Promise.all([
  mkdir(configurationRoot, { recursive: true }),
  mkdir(resolve(runtimeRoot, "cache", "proxy"), { recursive: true }),
  mkdir(resolve(runtimeRoot, "data", "audit"), { recursive: true }),
  mkdir(resolve(runtimeRoot, "data", "backups"), { recursive: true }),
  mkdir(resolve(runtimeRoot, "data", "blobs"), { recursive: true }),
  mkdir(resolve(runtimeRoot, "data", "blob-staging"), { recursive: true }),
]);

await Promise.all([
  writeConfiguration(
    resolve(configurationRoot, "backend.yaml"),
    backendConfiguration(publicOrigin),
  ),
  writeConfiguration(
    resolve(configurationRoot, "proxy.yaml"),
    proxyConfiguration(),
  ),
]);

process.stdout.write(
  `Prepared development configuration for ${publicOrigin}.\n`,
);

/** Rejects origins that cannot be compared exactly by the backend. */
function validatePublicOrigin(value) {
  const url = new URL(value);
  if (
    (url.protocol !== "http:" && url.protocol !== "https:") ||
    url.origin !== value
  ) {
    throw new Error(
      "APINTERACT_DEV_PUBLIC_ORIGIN must be an HTTP origin without a path",
    );
  }
}

/** Builds the local backend configuration without environment overrides. */
function backendConfiguration(origin) {
  return {
    configVersion: 1,
    server: {
      host: "0.0.0.0",
      port: 8080,
      publicOrigin: origin,
    },
    persistence: {
      databasePath: resolve(runtimeRoot, "data", "apinteract.sqlite3"),
      migrationBackupDirectory: resolve(runtimeRoot, "data", "backups"),
    },
    blobs: {
      rootPath: resolve(runtimeRoot, "data", "blobs"),
      stagingPath: resolve(runtimeRoot, "data", "blob-staging"),
    },
    audit: {
      rootPath: resolve(runtimeRoot, "data", "audit"),
    },
    proxy: {
      endpoint: "http://127.0.0.1:8081",
      bearerToken: "development-backend-token",
    },
    sessions: {
      secureCookie: false,
    },
    frontend: {
      distPath: resolve(repositoryRoot, "apps", "frontend", "dist"),
    },
    plugins: {
      builtinPath: resolve(repositoryRoot, "plugins"),
      userPath: resolve(runtimeRoot, "data", "plugins"),
    },
  };
}

/** Builds the local proxy configuration for the development backend. */
function proxyConfiguration() {
  return {
    configVersion: 1,
    server: {
      host: "0.0.0.0",
      port: 8081,
    },
    cache: {
      path: resolve(runtimeRoot, "cache", "proxy"),
    },
    targetPolicy: {
      privateNetworkAccess: "allow",
      allowCidrs: [],
      denyCidrs: [],
    },
    principals: [
      {
        id: "development-backend",
        bearerToken: "development-backend-token",
      },
    ],
  };
}

/** Writes one generated YAML file with owner-only permissions. */
async function writeConfiguration(path, configuration) {
  const header =
    "# Generated by pnpm dev:prepare. Configure development through deploy/development/.env.local.\n";
  // JSON syntax is a strict subset of YAML 1.2, so configuration stays
  // structured without adding a tooling-only serializer dependency.
  await writeFile(
    path,
    header + JSON.stringify(configuration, null, 2) + "\n",
    {
      encoding: "utf8",
      mode: 0o600,
    },
  );
}
